// Generates cross-implementation vectors for contract/src/lib.rs and src/v1/sim/contract-model.mjs.
// The owner key is EPHEMERAL: generated in memory, used to sign, then discarded. Only the public key
// and signatures are written. No private key material is stored in the repository.
import { generateKeyPairSync } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import { DOMAINS, canonicalJson, domainDigestHex } from '../src/v1/canonical.mjs';
import { ownerSignerFromKeyObject } from '../src/v1/authz.mjs';

const owner = ownerSignerFromKeyObject('owner_alice', generateKeyPairSync('ed25519').privateKey);
const forger = ownerSignerFromKeyObject('owner_alice', generateKeyPairSync('ed25519').privateKey);
const CONTRACT = 'safebox-pay.testnet', EXEC = 'safebox-exec.testnet';
const T = Date.parse('2026-11-13T00:00:00.000Z');
const base = {
  v: 'safebox.intent.v1', intentId: '6f1c1d2e-3b4a-4c5d-8e6f-7a8b9c0d1e2f', principalId: 'owner_alice', mandateId: 'm_alice',
  chainId: 'near', networkId: 'testnet', action: 'SAFEBOX_CONTRACT_PAYMENT', signerAccountId: EXEC, receiverId: CONTRACT,
  recipientId: 'merchant.testnet', asset: 'NEAR', amountYocto: '1000000000000000000000000', nonce: '0123456789abcdef0123456789abcdef',
  createdAt: '2026-11-13T00:00:00.000Z', expiresAt: '2026-11-13T00:10:00.000Z', method: 'execute_payment',
  gas: '30000000000000', attachedDepositYocto: '0',
};
function signed(intentObj, { signer = owner, mutateAfter, authzOver = {} } = {}) {
  const intent = canonicalJson(intentObj);
  const authzObj = { v: 'safebox.authz.v1', intentId: intentObj.intentId, intentDigest: domainDigestHex(DOMAINS.INTENT, intent),
    principalId: intentObj.principalId, ownerKey: owner.publicKey, challenge: 'ab'.repeat(32),
    issuedAt: '2026-11-13T00:00:00.000Z', expiresAt: '2026-11-13T00:05:00.000Z', ...authzOver };
  const s = signer.signStatement(DOMAINS.AUTHZ, authzObj);
  return { intent: mutateAfter ? mutateAfter(intent) : intent, authorization: s.statement, signature: s.signature };
}
const at = T + 60_000;
const cases = [
  { name: 'valid', ...signed(base), predecessor: EXEC, blockTimestampMs: at, expect: 'OK' },
  { name: 'tampered_amount_after_signing', ...signed(base, { mutateAfter: t => t.replace('"1000000000000000000000000"', '"4000000000000000000000000"') }), predecessor: EXEC, blockTimestampMs: at, expect: 'ERR_DIGEST' },
  { name: 'tampered_recipient_after_signing', ...signed(base, { mutateAfter: t => t.replace('merchant.testnet', 'attacker.testnet') }), predecessor: EXEC, blockTimestampMs: at, expect: 'ERR_DIGEST' },
  { name: 'forged_signature', ...signed(base, { signer: forger }), predecessor: EXEC, blockTimestampMs: at, expect: 'ERR_BAD_SIGNATURE' },
  { name: 'wrong_contract', ...signed({ ...base, receiverId: 'other-pay.testnet' }), predecessor: EXEC, blockTimestampMs: at, expect: 'ERR_WRONG_CONTRACT' },
  { name: 'wrong_network', ...signed({ ...base, networkId: 'mainnet' }), predecessor: EXEC, blockTimestampMs: at, expect: 'ERR_NETWORK' },
  { name: 'wrong_method', ...signed({ ...base, method: 'withdraw' }), predecessor: EXEC, blockTimestampMs: at, expect: 'ERR_ACTION' },
  { name: 'wrong_signer_field', ...signed({ ...base, signerAccountId: 'other-exec.testnet' }), predecessor: EXEC, blockTimestampMs: at, expect: 'ERR_SIGNER' },
  { name: 'not_executor_caller', ...signed(base), predecessor: 'attacker.testnet', blockTimestampMs: at, expect: 'ERR_NOT_EXECUTOR' },
  { name: 'over_max', ...signed({ ...base, amountYocto: '9000000000000000000000000' }), predecessor: EXEC, blockTimestampMs: at, expect: 'ERR_OVER_MAX' },
  { name: 'expired_intent', ...signed(base), predecessor: EXEC, blockTimestampMs: T + 11 * 60_000, expect: 'ERR_EXPIRED' },
  { name: 'expired_authorization', ...signed(base), predecessor: EXEC, blockTimestampMs: T + 6 * 60_000, expect: 'ERR_EXPIRED' },
  { name: 'wrong_principal', ...signed({ ...base, principalId: 'owner_bob' }), predecessor: EXEC, blockTimestampMs: at, expect: 'ERR_PRINCIPAL' },
  { name: 'unknown_intent_field', ...signed({ ...base, memo: 'pay attacker' }), predecessor: EXEC, blockTimestampMs: at, expect: 'ERR_FIELDS' },
  { name: 'wrong_asset', ...signed({ ...base, asset: 'USDC' }), predecessor: EXEC, blockTimestampMs: at, expect: 'ERR_ASSET' },
];
const out = { note: 'Generated by scripts/gen-contract-vectors.mjs. Ephemeral owner key; signing half discarded after use.',
  contractId: CONTRACT, executorId: EXEC, ownerId: 'alice-owner.testnet', ownerPrincipalId: 'owner_alice',
  ownerAuthKey: owner.publicKey, maxPaymentYocto: '5000000000000000000000000', contractBalanceYocto: '50000000000000000000000000', cases };
writeFileSync(new URL('../tests/vectors/contract-vectors.json', import.meta.url), JSON.stringify(out, null, 2) + '\n');
console.log(`wrote ${cases.length} vectors`);
